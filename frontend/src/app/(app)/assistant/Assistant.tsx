"use client";

import { useMutation, useQuery } from "@tanstack/react-query";
import clsx from "clsx";
import { Activity, BookOpen, Database, Info, Send } from "lucide-react";
import { useRouter, useSearchParams } from "next/navigation";
import { useState } from "react";

import { Button, Card, EmptyState, ErrorState, Input, PageHeader, Spinner, Table, Tag, Td, Th } from "@/components/ui";
import { api, openManual } from "@/lib/api";
import type { Anomaly, QueryResult, RagAnswer } from "@/lib/types";

const TABS = [
  { id: "manuals", label: "Ask the manuals", Icon: BookOpen },
  { id: "data", label: "Ask the data", Icon: Database },
  { id: "anomalies", label: "Flight data anomalies", Icon: Activity },
] as const;

function ProviderNote({ provider, degraded }: { provider: string; degraded: boolean }) {
  return (
    <p className="mt-3 flex items-center gap-1 text-xs text-muted">
      <Info aria-hidden className="size-3.5" />
      {provider === "mock"
        ? "Offline mode: deterministic answer, no LLM used."
        : degraded
          ? "The AI service was unavailable: showing the deterministic fallback."
          : `Generated by ${provider}. Check citations before acting.`}
    </p>
  );
}

export function Assistant() {
  const params = useSearchParams();
  const router = useRouter();
  const tab = (TABS.find((t) => t.id === params.get("tab"))?.id ?? "manuals") as (typeof TABS)[number]["id"];

  return (
    <>
      <PageHeader
        title="AI assistant"
        subtitle="Advisory only. Airworthiness decisions are made by certifying staff following the approved manuals."
      />
      <div role="tablist" aria-label="Assistant mode" className="mb-4 flex flex-wrap gap-1">
        {TABS.map(({ id, label, Icon }) => (
          <button
            key={id}
            role="tab"
            id={`tab-${id}`}
            aria-selected={tab === id}
            aria-controls={`panel-${id}`}
            onClick={() => router.replace(`/assistant?tab=${id}`)}
            className={clsx(
              "flex cursor-pointer items-center gap-2 rounded-md px-3 py-1.5 text-sm",
              tab === id ? "bg-primary text-primary-fg" : "text-muted hover:bg-surface-2",
            )}
          >
            <Icon aria-hidden className="size-4" /> {label}
          </button>
        ))}
      </div>
      <div role="tabpanel" id={`panel-${tab}`} aria-labelledby={`tab-${tab}`}>
        {tab === "manuals" && <AskManuals />}
        {tab === "data" && <AskData />}
        {tab === "anomalies" && <Anomalies />}
      </div>
    </>
  );
}

function QuestionBox({
  placeholder,
  examples,
  busy,
  onAsk,
}: {
  placeholder: string;
  examples: string[];
  busy: boolean;
  onAsk: (q: string) => void;
}) {
  const [q, setQ] = useState("");
  return (
    <div className="mb-4 space-y-2">
      <form
        className="flex gap-2"
        onSubmit={(e) => {
          e.preventDefault();
          if (q.trim()) onAsk(q.trim());
        }}
      >
        <Input aria-label="Question" placeholder={placeholder} value={q} onChange={(e) => setQ(e.target.value)} maxLength={1000} />
        <Button type="submit" variant="primary" loading={busy} disabled={!q.trim()}>
          <Send aria-hidden className="size-4" /> Ask
        </Button>
      </form>
      <div className="flex flex-wrap gap-1">
        {examples.map((ex) => (
          <button
            key={ex}
            onClick={() => {
              setQ(ex);
              onAsk(ex);
            }}
            className="cursor-pointer rounded-full border border-border px-3 py-1 text-xs text-muted hover:border-muted hover:text-fg"
          >
            {ex}
          </button>
        ))}
      </div>
    </div>
  );
}

/** Render "[2]" markers as buttons that open the cited page. */
function WithCitations({ text, answer }: { text: string; answer: RagAnswer }) {
  const byN = new Map(answer.citations.map((c) => [c.n, c]));
  const parts = text.split(/(\[\d+\])/g);
  return (
    <>
      {parts.map((part, i) => {
        const m = part.match(/^\[(\d+)\]$/);
        const c = m ? byN.get(Number(m[1])) : undefined;
        if (!c) return <span key={i}>{part}</span>;
        return (
          <button
            key={i}
            onClick={() => openManual(c.document_id, c.page)}
            className="mx-0.5 cursor-pointer rounded bg-primary/15 px-1 text-xs font-medium text-primary hover:bg-primary/25"
            title={`${c.title}, page ${c.page}`}
          >
            {c.n}
          </button>
        );
      })}
    </>
  );
}

function AskManuals() {
  const m = useMutation({ mutationFn: (question: string) => api<RagAnswer>("/api/ai/ask/", { method: "POST", body: { question } }) });
  return (
    <Card>
      <QuestionBox
        placeholder="e.g. What torque for the oil drain plug?"
        examples={["What torque for the oil drain plug?", "Maximum propeller vibration?", "How often is the battery capacity tested?"]}
        busy={m.isPending}
        onAsk={(q) => m.mutate(q)}
      />
      {m.isPending && <Spinner label="Searching manuals…" />}
      {m.error && <ErrorState error={m.error} />}
      {m.data && (
        <div aria-live="polite">
          <div className="rounded-md border border-border bg-surface-2 p-4 text-sm leading-relaxed whitespace-pre-line">
            <WithCitations text={m.data.answer} answer={m.data} />
          </div>
          {m.data.citations.length > 0 && (
            <div className="mt-4">
              <p className="mb-2 text-xs font-semibold text-muted uppercase">Sources</p>
              <ul className="space-y-2">
                {m.data.citations.map((c) => (
                  <li key={c.n} className="text-sm">
                    <button onClick={() => openManual(c.document_id, c.page)} className="cursor-pointer text-left text-primary hover:underline">
                      [{c.n}] {c.title}, page {c.page}
                    </button>
                    <p className="line-clamp-2 text-xs text-muted">{c.snippet}</p>
                  </li>
                ))}
              </ul>
            </div>
          )}
          <ProviderNote provider={m.data.provider} degraded={m.data.degraded} />
        </div>
      )}
    </Card>
  );
}

function cell(v: unknown): string {
  if (v === null || v === undefined || v === "") return "—";
  if (typeof v === "string" && /^\d{4}-\d{2}-\d{2}T/.test(v)) return new Date(v).toLocaleString("en-GB");
  return String(v);
}

function AskData() {
  const m = useMutation({ mutationFn: (question: string) => api<QueryResult>("/api/ai/query/", { method: "POST", body: { question } }) });
  const cols = m.data?.rows[0] ? Object.keys(m.data.rows[0]) : [];
  return (
    <Card>
      <QuestionBox
        placeholder="e.g. Hangi uçaklar yerde? / Which work orders are awaiting inspection?"
        examples={["Hangi uçaklar yerde?", "Gecikmiş bakımlar neler?", "Open work orders awaiting inspection", "Components with less than 100 hours of life", "Düşük stoklu yedek parçalar"]}
        busy={m.isPending}
        onAsk={(q) => m.mutate(q)}
      />
      {m.isPending && <Spinner label="Interpreting…" />}
      {m.error && <ErrorState error={m.error} />}
      {m.data && (
        <div aria-live="polite">
          <div className="mb-3 flex flex-wrap items-center gap-2 text-sm">
            <span className="text-muted">Interpreted as:</span>
            <Tag tone="info">{m.data.spec.entity.replace("_", " ")}</Tag>
            {Object.entries(m.data.spec.filters)
              .filter(([, v]) => v !== null && v !== "" && v !== false)
              .map(([k, v]) => (
                <Tag key={k}>
                  {k}={String(v)}
                </Tag>
              ))}
            <span className="text-muted">· {m.data.count} result(s)</span>
          </div>
          {m.data.spec.explanation && <p className="mb-3 text-sm">{m.data.spec.explanation}</p>}
          {m.data.rows.length === 0 ? (
            <EmptyState>No matching records.</EmptyState>
          ) : (
            <Table>
              <thead>
                <tr>
                  {cols.map((c) => (
                    <Th key={c}>{c.replaceAll("_", " ")}</Th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {m.data.rows.map((r, i) => (
                  <tr key={i}>
                    {cols.map((c) => (
                      <Td key={c} className="text-xs">
                        {cell(r[c])}
                      </Td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </Table>
          )}
          <ProviderNote provider={m.data.provider} degraded={m.data.degraded} />
        </div>
      )}
    </Card>
  );
}

function Anomalies() {
  const q = useQuery({ queryKey: ["anomalies"], queryFn: () => api<Anomaly[]>("/api/ai/anomalies/") });
  if (q.isPending) return <Spinner />;
  if (q.error) return <ErrorState error={q.error} />;
  if (q.data.length === 0)
    return (
      <Card>
        <EmptyState>No unusual flight data in the last flights of any active aircraft.</EmptyState>
      </Card>
    );
  return (
    <div className="space-y-4">
      <p className="text-sm text-muted">
        Detected by statistics (robust z-score of the last 5 flights vs the 30 before). The AI only explains.
      </p>
      {q.data.map((a) => (
        <AnomalyCard key={a.key} a={a} />
      ))}
    </div>
  );
}

function AnomalyCard({ a }: { a: Anomaly }) {
  const m = useMutation({
    mutationFn: () =>
      api<{ explanation: string; provider: string; degraded: boolean }>("/api/ai/anomalies/explain/", {
        method: "POST",
        body: { aircraft: a.aircraft_id, metric: a.metric },
      }),
  });
  const max = Math.max(...a.recent_values, a.baseline_median);
  return (
    <Card title={`${a.tail_number}: ${a.label} unusually ${a.direction}`}>
      <div className="mb-3 flex items-end gap-2" role="img" aria-label={`Last flights: ${a.recent_values.join(", ")} ${a.unit}; normal ${a.baseline_median}`}>
        {a.recent_values.map((v, i) => (
          <div key={i} className="flex flex-col items-center gap-1">
            <span className="tabular text-xs">{v}</span>
            <div
              className={clsx("w-8 rounded-t", Math.abs(a.recent_z[i]) > 3.5 ? "bg-warn" : "bg-primary")}
              style={{ height: `${Math.max(4, (v / max) * 64)}px` }}
            />
            <span className="text-[10px] text-muted">z {a.recent_z[i]}</span>
          </div>
        ))}
        <div className="ml-3 text-xs text-muted">
          normal (median)
          <br />
          <span className="tabular text-sm text-fg">
            {a.baseline_median} {a.unit}
          </span>
        </div>
      </div>
      <p className="mb-3 text-xs text-muted">Bars over |z| 3.5 are marked amber.</p>
      {!m.data && (
        <Button onClick={() => m.mutate()} loading={m.isPending}>
          Explain
        </Button>
      )}
      {m.error && <ErrorState error={m.error} />}
      {m.data && (
        <div aria-live="polite">
          <div className="rounded-md border border-border bg-surface-2 p-4 text-sm whitespace-pre-line">{m.data.explanation}</div>
          <ProviderNote provider={m.data.provider} degraded={m.data.degraded} />
        </div>
      )}
    </Card>
  );
}
